import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import CustomFoods from '@/pages/Food/CustomFoods'
import ExerciseLibrary from '@/pages/Exercise/ExerciseLibrary'

const createFood = jest.fn(), deleteFood = jest.fn(), saveExercise = jest.fn()
const fetchFoods = jest.fn(), fetchSavedExercises = jest.fn()
jest.mock('@/store/foodStore', () => ({ useFoodStore: () => ({ foods: [{ id: '1', name: 'Apple', calories: 100, protein_g: 0, carbs_g: 0, fat_g: 0 }], isLoading: false, fetchFoods, createFood, deleteFood }) }))
jest.mock('@/store/exerciseStore', () => ({ useExerciseStore: () => ({ savedExercises: [], isLoading: false, fetchSavedExercises, saveExercise, deleteSavedExercise: jest.fn() }) }))
const deferred = () => { let resolve!: (value?: any) => void; let reject!: (reason: unknown) => void; const promise = new Promise<any>((yes, no) => { resolve = yes; reject = no }); return { promise, resolve, reject } }
beforeEach(() => { jest.clearAllMocks() })

test('custom food save locks synchronous double submission, preserves draft/error, and closes only on success', async () => {
  const save = deferred()
  createFood.mockReturnValueOnce(save.promise).mockResolvedValueOnce({ id: 'new' })
  render(<CustomFoods />)
  fireEvent.click(screen.getByRole('button', { name: 'Add Food', exact: true }))
  const dialog = screen.getByRole('dialog')
  const name = screen.getByPlaceholderText('e.g. Grilled Chicken Breast')
  fireEvent.change(name, { target: { value: 'Lunch draft' } })
  fireEvent.change(screen.getByPlaceholderText('e.g. 165'), { target: { value: '165' } })
  fireEvent.submit(dialog.querySelector('form')!); fireEvent.submit(dialog.querySelector('form')!)
  await screen.findByRole('button', { name: 'Saving…' })
  expect(createFood).toHaveBeenCalledTimes(1)
  expect(within(dialog).getByRole('button', { name: 'Saving…' })).toBeDisabled()
  expect(dialog.querySelectorAll('svg.animate-spin')).toHaveLength(1)
  fireEvent.keyDown(document, { key: 'Escape' })
  expect(dialog).toBeInTheDocument()
  await act(async () => save.reject({ response: { data: { error: 'Offline, retry' } } }))
  expect(screen.getByRole('alert')).toHaveTextContent('Offline, retry')
  expect(name).toHaveValue('Lunch draft')
  fireEvent.click(within(dialog).getByRole('button', { name: 'Add Food' }))
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
})

test('custom food delete waits, retains failure and allows retry', async () => {
  const deletion = deferred()
  deleteFood.mockReturnValueOnce(deletion.promise).mockResolvedValueOnce(undefined)
  render(<CustomFoods />)
  fireEvent.click(screen.getByRole('button', { name: 'Delete Apple' }))
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Delete', exact: true }))
  expect(screen.getByRole('button', { name: 'Deleting…' })).toBeDisabled()
  await act(async () => deletion.reject({ response: { data: { error: 'Cannot delete yet' } } }))
  expect(screen.getByRole('alert')).toHaveTextContent('Cannot delete yet')
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Delete', exact: true }))
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  expect(deleteFood).toHaveBeenCalledTimes(2)
})

test('exercise add shows Saving and guards duplicate submissions until success', async () => {
  const save = deferred()
  saveExercise.mockReturnValueOnce(save.promise)
  render(<ExerciseLibrary />)
  fireEvent.click(screen.getAllByRole('button', { name: 'Add Exercise', exact: true })[0])
  const dialog = screen.getByRole('dialog')
  fireEvent.change(screen.getByPlaceholderText('e.g. Bench Press'), { target: { value: 'My lift' } })
  const selects = dialog.querySelectorAll('select')
  fireEvent.change(selects[0], { target: { value: 'chest' } })
  fireEvent.change(selects[1], { target: { value: 'strength' } })
  fireEvent.submit(dialog.querySelector('form')!); fireEvent.submit(dialog.querySelector('form')!)
  await screen.findByRole('button', { name: 'Saving…' })
  expect(saveExercise).toHaveBeenCalledTimes(1)
  await act(async () => save.resolve(true))
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
})
